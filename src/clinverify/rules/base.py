"""Rule interface for the team-written rule catalog.

A rule is a named, sourced constraint over a Plan, expressed as a Z3 Boolean expression that must hold for the plan
to be valid. Rules are written and reviewed by the team (never generated by the model). Registration enforces the
project requirement "rules have IDs and supporting sources".

See docs/rule_authoring.md for how to add a rule.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Callable

import z3

from clinverify.plan import Plan

ID_PATTERN = re.compile(r"^R-[A-Z]{2,8}-\d{3}$")     # e.g. R-LAB-001


@dataclass(frozen=True)
class Rule:
    id: str                                          # unique, e.g. R-LAB-001
    description: str                                 # one sentence: what must hold
    source: str                                      # guideline, paper or clinical reference that justifies the rule
    requires: tuple[str, ...]                        # Plan fields the rule needs; if absent the rule is inconclusive
    constraint: Callable[[Plan], z3.BoolRef]         # builds the Z3 expression that must be satisfiable


class RuleCatalog:
    def __init__(self) -> None:
        self._rules: dict[str, Rule] = {}

    def register(self, id: str, description: str, source: str, requires: tuple[str, ...] = ()):
        """Decorator: @catalog.register("R-LAB-001", "...", "source", requires=("labs",))"""
        def wrap(fn: Callable[[Plan], z3.BoolRef]) -> Callable[[Plan], z3.BoolRef]:
            self.add(Rule(id, description, source, tuple(requires), fn))
            return fn
        return wrap

    def add(self, rule: Rule) -> None:
        if not ID_PATTERN.match(rule.id):
            raise ValueError(f"rule id {rule.id!r} must look like R-LAB-001")
        if rule.id in self._rules:
            raise ValueError(f"duplicate rule id {rule.id}")
        if not rule.description.strip():
            raise ValueError(f"{rule.id}: description is empty")
        if not rule.source.strip():
            raise ValueError(f"{rule.id}: every rule needs a supporting source")
        unknown = [f for f in rule.requires if f not in Plan.__dataclass_fields__]
        if unknown:
            raise ValueError(f"{rule.id}: requires unknown Plan fields {unknown}")
        self._rules[rule.id] = rule

    def __iter__(self):
        return iter(self._rules.values())

    def __len__(self) -> int:
        return len(self._rules)

    def get(self, rule_id: str) -> Rule:
        return self._rules[rule_id]
